"""LLM-as-a-Judge Faithfulness & Hallucination Auditor."""

import os
import json
import re
from typing import List, Dict, Any, Literal
from pydantic import BaseModel, Field
from src.config import settings

VerdictType = Literal["SUPPORTED", "CONTRADICTED", "NOT_SUPPORTED"]

class ClaimAudit(BaseModel):
    claim: str
    cited_chunk_id: str = ""
    verdict: VerdictType
    reasoning: str

class FaithfulnessReport(BaseModel):
    total_claims: int
    supported_claims: int
    faithfulness_score: float
    is_faithful: bool
    audits: List[ClaimAudit] = Field(default_factory=list)
    judge_model: str = ""

FAITHFULNESS_JUDGE_PROMPT = """You are an impartial academic verification judge evaluating factual faithfulness in RAG systems.

Given:
1. An answer generated by an AI assistant.
2. The exact retrieved context passages provided to the assistant.

Your task:
1. Break down the answer into distinct, atomic factual claims.
2. For each claim, determine whether it is strictly supported by the context passages.
3. Classify each claim into one of three verdicts:
   - "SUPPORTED": The claim is directly substantiated by the provided passages.
   - "CONTRADICTED": The claim contradicts the provided passages.
   - "NOT_SUPPORTED": The claim makes assertions or introduces details not mentioned in the passages.

Output strictly valid JSON with this schema:
{
  "audits": [
    {
      "claim": "string",
      "cited_chunk_id": "string",
      "verdict": "SUPPORTED" | "CONTRADICTED" | "NOT_SUPPORTED",
      "reasoning": "brief explanation"
    }
  ]
}
"""

class FaithfulnessJudge:
    def __init__(self):
        self.provider = settings.LLM_PROVIDER
        self.gemini_key = settings.GEMINI_API_KEY or os.getenv("GEMINI_API_KEY", "")
        self.openai_key = settings.OPENAI_API_KEY or os.getenv("OPENAI_API_KEY", "")

    def _extract_sentences(self, text: str) -> List[str]:
        """Split answer into sentence-level claims."""
        sentences = re.split(r"(?<=[.?!])\s+", text)
        return [s.strip() for s in sentences if len(s.strip().split()) >= 4]

    def _heuristic_audit(self, answer: str, context_chunks: List[Dict[str, Any]]) -> FaithfulnessReport:
        """Rule-based token/n-gram containment audit when no LLM API key is configured."""
        sentences = self._extract_sentences(answer)
        if not sentences:
            return FaithfulnessReport(
                total_claims=0,
                supported_claims=0,
                faithfulness_score=1.0,
                is_faithful=True,
                audits=[],
                judge_model="heuristic-rule-engine"
            )

        combined_context = " ".join([c.get("text", "") for c in context_chunks]).lower()
        audits: List[ClaimAudit] = []
        supported_count = 0

        for sent in sentences:
            # Clean punctuation and check significant word overlap
            words = [w.lower() for w in re.findall(r"\b[a-zA-Z0-9_-]+\b", sent) if len(w) > 3]
            if not words:
                continue

            matches = sum(1 for w in words if w in combined_context)
            overlap_ratio = matches / len(words)

            if overlap_ratio >= 0.5:
                verdict = "SUPPORTED"
                reasoning = f"High keyword alignment ({overlap_ratio:.1%}) with retrieved passage."
                supported_count += 1
            else:
                verdict = "NOT_SUPPORTED"
                reasoning = f"Low context overlap ({overlap_ratio:.1%}); statement may contain ungrounded details."

            audits.append(ClaimAudit(
                claim=sent,
                cited_chunk_id=context_chunks[0].get("chunk_id", "") if context_chunks else "",
                verdict=verdict,
                reasoning=reasoning
            ))

        total = len(audits)
        score = supported_count / total if total > 0 else 1.0

        return FaithfulnessReport(
            total_claims=total,
            supported_claims=supported_count,
            faithfulness_score=round(score, 3),
            is_faithful=(score >= 0.75),
            audits=audits,
            judge_model="heuristic-rule-engine"
        )

    def evaluate(self, answer: str, context_chunks: List[Dict[str, Any]]) -> FaithfulnessReport:
        """Run faithfulness evaluation using LLM-as-a-judge (or heuristic fallback)."""
        if not self.gemini_key and not self.openai_key:
            return self._heuristic_audit(answer, context_chunks)

        context_text = "\n\n".join([f"[{c.get('paper_id')} | {c.get('section_title')}]: {c.get('text')}" for c in context_chunks])
        prompt = f"RETRIEVED CONTEXT:\n{context_text}\n\nGENERATED ANSWER TO AUDIT:\n{answer}"

        if self.gemini_key and self.provider == "gemini":
            try:
                from google import genai
                client = genai.Client(api_key=self.gemini_key)
                response = client.models.generate_content(
                    model=settings.FAITHFULNESS_JUDGE_MODEL,
                    contents=prompt,
                    config={
                        "system_instruction": FAITHFULNESS_JUDGE_PROMPT,
                        "response_mime_type": "application/json"
                    }
                )
                raw_json = json.loads(response.text or "{}")
                audits = [ClaimAudit(**a) for a in raw_json.get("audits", [])]
                total = len(audits)
                supported = sum(1 for a in audits if a.verdict == "SUPPORTED")
                score = supported / total if total > 0 else 1.0
                return FaithfulnessReport(
                    total_claims=total,
                    supported_claims=supported,
                    faithfulness_score=round(score, 3),
                    is_faithful=(score >= 0.75),
                    audits=audits,
                    judge_model=settings.FAITHFULNESS_JUDGE_MODEL
                )
            except Exception as e:
                print(f"[WARN] LLM judge failed: {e}. Falling back to heuristic auditor.")
                return self._heuristic_audit(answer, context_chunks)

        return self._heuristic_audit(answer, context_chunks)
